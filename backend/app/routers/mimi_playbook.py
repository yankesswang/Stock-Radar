def get_live_prices():
    """Fetch live prices for all mimi-tracked US tickers via yfinance."""
    prices = {}
    try:
        data = yf.download(
            tickers=" ".join(TICKERS),
            period="1d",
            interval="1d",
            progress=False,
            auto_adjust=True,
        )
        if data is None or data.empty:
            raise ValueError("no data")
        import pandas as pd  # noqa: PLC0415
        assert isinstance(data, pd.DataFrame)
        close = data["Close"]
        for ticker in TICKERS:
            try:
                col = close[ticker]
                vals = [v for v in col.tolist() if v is not None and str(v) != "nan"]
                prices[ticker] = round(float(vals[-1]), 2) if vals else None
            except (KeyError, IndexError, TypeError):
                prices[ticker] = None
    except Exception:
        for ticker in TICKERS:
            prices[ticker] = None
    return {"prices": prices}


@router.get("/fundamentals")
def get_fundamentals():
    """Fetch YTD perf, fwd PE, beta, 52W high/low, market cap for all mimi tickers."""
    import math
    import datetime
    import pandas as pd  # noqa: PLC0415
    from concurrent.futures import ThreadPoolExecutor

    year_start = f"{datetime.date.today().year}-01-01"
    ytd: dict[str, float | None] = {}

    # Batch YTD price history since Jan 1
    try:
        ytd_data = yf.download(
            tickers=" ".join(TICKERS),
            start=year_start,
            progress=False,
            auto_adjust=True,
        )
        if ytd_data is not None and not ytd_data.empty:
            assert isinstance(ytd_data, pd.DataFrame)
            close_ytd = ytd_data["Close"]
            for ticker in TICKERS:
                try:
                    col = close_ytd[ticker]
                    vals = [
                        float(v) for v in col.tolist()
                        if v is not None and str(v) != "nan" and not math.isnan(float(v))
                    ]
                    ytd[ticker] = round((vals[-1] / vals[0] - 1) * 100, 1) if len(vals) >= 2 else None
                except (KeyError, TypeError, ValueError, ZeroDivisionError):
                    ytd[ticker] = None
    except Exception:
        for t in TICKERS:
            ytd[t] = None

    # Parallel .info fetch for PE, beta, 52W range, market cap
    def fetch_info(ticker: str) -> tuple[str, dict]:
        try:
            info = yf.Ticker(ticker).info

            def safe(val: object) -> float | None:
                try:
                    f = float(val)  # type: ignore[arg-type]
                    return None if math.isnan(f) else f
                except (TypeError, ValueError):
                    return None

            return ticker, {
                "fwd_pe":      round(safe(info.get("forwardPE")) or 0, 1) or None,
                "beta":        round(safe(info.get("beta")) or 0, 2) or None,
                "week52_high": safe(info.get("fiftyTwoWeekHigh")),
                "week52_low":  safe(info.get("fiftyTwoWeekLow")),
                "market_cap":  int(info["marketCap"]) if info.get("marketCap") else None,
            }
        except Exception:
            return ticker, {}

    with ThreadPoolExecutor(max_workers=12) as executor:
        info_map = dict(executor.map(fetch_info, TICKERS))

    fundamentals: dict[str, dict] = {}
    for ticker in TICKERS:
        inf = info_map.get(ticker, {})
        fundamentals[ticker] = {
            "ytd_pct":    ytd.get(ticker),
            "fwd_pe":     inf.get("fwd_pe"),
            "beta":       inf.get("beta"),
            "week52_high": inf.get("week52_high"),
            "week52_low":  inf.get("week52_low"),
            "market_cap":  inf.get("market_cap"),
        }

    return {"fundamentals": fundamentals}
