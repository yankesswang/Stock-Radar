def _split_analysis_by_marker(
    analysis: str, date_str: str, portfolio_names: list[str]
) -> list[tuple[str, str]]:
    """
    Split Claude's response into independent Telegram messages by <<<MARKER>>> lines.

    Expected output structure from Claude:
        <<<SHARED>>>   → 大盤形勢判讀
        <<<MAIN>>>     → Main 組合完整分析
        <<<MOM>>>      → Mom 組合完整分析
        <<<MIMI>>>     → Mimi 觀察名單機會

    Returns list of (label, message_text) tuples; falls back to single message if no markers.
    """
    MARKER_RE = re.compile(r"^<<<([A-Z_]+)>>>", re.MULTILINE)
    matches = list(MARKER_RE.finditer(analysis))

    if not matches:
        return [("全部", f"🤖 收盤分析｜{date_str}\n\n{analysis}")]

    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        key = m.group(1)
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(analysis)
        sections[key] = analysis[start:end].strip()

    result: list[tuple[str, str]] = []

    # Message 1: 大盤形勢
    if body := sections.get("SHARED", ""):
        result.append(("大盤形勢", f"🤖 收盤分析｜{date_str}\n\n{body}"))

    # Message 2+: one per portfolio
    for pname in portfolio_names:
        key = pname.upper().replace(" ", "_")
        if body := sections.get(key, ""):
            result.append((f"{pname} 組合", f"📊 {pname} 組合｜{date_str}\n\n{body}"))

    # Message N: Mimi 觀察名單
    if body := sections.get("MIMI", ""):
        result.append(("Mimi 觀察名單", f"🔍 Mimi 觀察名單｜{date_str}\n\n{body}"))

    # Fallback: anything else
    known = {"SUMMARY", "SHARED", "MIMI"} | {p.upper().replace(" ", "_") for p in portfolio_names}
    for key, body in sections.items():
        if key not in known and body:
            result.append((key, body))

    return result if result else [("全部", f"🤖 收盤分析｜{date_str}\n\n{analysis}")]


