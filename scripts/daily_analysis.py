def _merge_analysis_into_portfolio(
    portfolio_md_raw: str,
    analysis: str,
    portfolio_names: list[str],
) -> str:
    """
    Stitch morning Portfolio.md table + Claude's analysis sections into one document.
    <<<MARKERS>>> are converted to ## headings; portfolio table stays verbatim.
    """
    MARKER_RE = re.compile(r"^<<<([A-Z_]+)>>>\s*\n", re.MULTILINE)
    matches = list(MARKER_RE.finditer(analysis))

    # Parse Claude sections
    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        key = m.group(1)
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(analysis)
        sections[key] = analysis[start:end].strip()

    parts: list[str] = []

    # Portfolio table from morning Stock Digest (strip its own frontmatter/title if present)
    table_body = re.sub(r"^---.*?---\s*", "", portfolio_md_raw, flags=re.DOTALL).strip()
    # Remove the H1 title line (we'll set our own)
    table_body = re.sub(r"^#\s+.*\n", "", table_body).strip()
    if table_body:
        parts.append(table_body)

    # 大盤形勢
    if body := sections.get("SHARED", ""):
        parts.append(f"---\n\n## 📊 大盤形勢\n\n{body}")

    # Per-portfolio analysis
    for pname in portfolio_names:
        key = pname.upper().replace(" ", "_")
        if body := sections.get(key, ""):
            parts.append(f"---\n\n## 💼 {pname} 組合分析\n\n{body}")

    # Mimi watchlist
    if body := sections.get("MIMI", ""):
        parts.append(f"---\n\n## 🔍 Mimi 觀察名單\n\n{body}")

    return "\n\n".join(parts)


