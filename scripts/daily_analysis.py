# ── Entry-zone proximity filter ───────────────────────────────────────────────

def _is_near_entry_zone(price: float | None, entry_text: str, threshold_pct: float = 15.0) -> bool:
    """True if price is inside or within threshold% below the Mimi entry zone."""
    if price is None:
        return False
    # "$80-95", "$35 – $42", "80~95" etc.
    ranges = re.findall(r"\$?([\d,]+(?:\.\d+)?)\s*[-–~～至到]\s*\$?([\d,]+(?:\.\d+)?)", entry_text)
    for lo_s, hi_s in ranges:
        try:
            lo = float(lo_s.replace(",", ""))
            hi = float(hi_s.replace(",", ""))
            if lo > hi:
                lo, hi = hi, lo
            if lo <= price <= hi:
                return True
            # Approaching from below: within threshold% under lo
            if price < lo and price >= lo * (1 - threshold_pct / 100):
                return True
            # Just above zone: within threshold% above hi (slightly overshot)
            if price > hi and price <= hi * (1 + threshold_pct / 100):
                return True
        except ValueError:
            continue
    # "$XX以下" / "$XX以內"
    singles = re.findall(r"\$?([\d,]+(?:\.\d+)?)\s*(?:以下|以內|below)", entry_text, re.IGNORECASE)
    for s in singles:
        try:
            target = float(s.replace(",", ""))
            if price <= target * (1 + threshold_pct / 100):
                return True
        except ValueError:
            continue
    return False


