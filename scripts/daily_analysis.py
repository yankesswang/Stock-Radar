def _md_to_html(text: str) -> str:
    """Convert Claude markdown output to Telegram-compatible HTML."""
    lines = text.split("\n")
    out: list[str] = []

    for line in lines:
        # Table separator rows (|---|---|) → skip
        if re.match(r"^\|[\s\-:|]+\|", line):
            continue

        # Table rows → "Key: Value" plain lines
        if line.startswith("|") and line.endswith("|") and "|" in line[1:-1]:
            cells = [c.strip() for c in line[1:-1].split("|")]
            cells = [c for c in cells if c]
            if len(cells) >= 2:
                key = re.sub(r"\*+", "", cells[0])  # strip markdown bold markers
                val = " | ".join(cells[1:])
                key = key.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                val = val.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                # Strip remaining **bold** from value
                val = re.sub(r"\*\*(.+?)\*\*", r"\1", val)
                out.append(f"  <b>{key}</b>: {val}")
            continue

        # Section headers (##, ###) → bold with leading newline
        m = re.match(r"^(#{1,4})\s+(.*)", line)
        if m:
            level = len(m.group(1))
            header = m.group(2).strip()
            header = header.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            prefix = "\n" if level <= 2 else ""
            out.append(f"{prefix}<b>{header}</b>")
            continue

        # Escape HTML special chars first, then apply inline formatting
        line = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        # **bold** → <b>bold</b>
        line = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", line)
        # *italic* (not inside **) → <i>italic</i>
        line = re.sub(r"(?<!\*)\*([^*\n]+?)\*(?!\*)", r"<i>\1</i>", line)
        # `code` → <code>code</code>
        line = re.sub(r"`([^`\n]+)`", r"<code>\1</code>", line)
        # Horizontal rules → separator line
        if re.match(r"^---+$", line.strip()):
            line = "─" * 20
        out.append(line)

    return "\n".join(out)


def send_telegram(text: str) -> None:
    token, chat_id = _get_telegram_config()
    if not token or not chat_id:
        print("[telegram] Not configured — printing to stdout only")
        print(text)
        return

    html_text = _md_to_html(text)

    LIMIT = 3900
    paras = html_text.split("\n\n")
    chunks: list[str] = []
    cur: list[str] = []
    cur_len = 0
    for para in paras:
        pl = len(para) + 2
        if cur_len + pl > LIMIT and cur:
            chunks.append("\n\n".join(cur))
            cur = [para]
            cur_len = pl
        else:
            cur.append(para)
            cur_len += pl
    if cur:
        chunks.append("\n\n".join(cur))

    total = len(chunks)
    print(f"[telegram] Sending {total} chunk(s)...")
    for i, chunk in enumerate(chunks):
        if i > 0:
            time.sleep(1)
        # Add chunk indicator footer when there are multiple chunks
        msg = chunk
        if total > 1:
            msg = f"{chunk}\n\n<i>── {i+1}/{total} ──</i>"
        try:
            r = requests.post(
                f"https://api.telegram.org/bot{token}/sendMessage",
                data={
                    "chat_id": chat_id,
                    "text": msg,
                    "parse_mode": "HTML",
                    "disable_web_page_preview": "true",
                },
                timeout=10,
            )
            r.raise_for_status()
            print(f"[telegram] Chunk {i+1}/{total} sent")
        except Exception as e:
            print(f"[telegram] Chunk {i+1} failed: {e}")
            # Fallback: retry without parse_mode if HTML caused the error
            if "can't parse" in str(e).lower() or "400" in str(e):
                try:
                    r2 = requests.post(
                        f"https://api.telegram.org/bot{token}/sendMessage",
                        data={"chat_id": chat_id, "text": chunk, "disable_web_page_preview": "true"},
                        timeout=10,
                    )
                    r2.raise_for_status()
                    print(f"[telegram] Chunk {i+1}/{total} sent (plain text fallback)")
                except Exception as e2:
                    print(f"[telegram] Chunk {i+1} plain fallback also failed: {e2}")


