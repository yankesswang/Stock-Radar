def parse_mimi_doc() -> dict[str, str]:
    """Return {TICKER: full_section_text} for all entries in the Mimi doc."""
    doc_path = Path(settings.MIMI_DOC_PATH).expanduser()
    if not doc_path.exists():
        print(f"[mimi] Doc not found: {doc_path}")
        return {}
    text = doc_path.read_text(encoding="utf-8")
    sections: dict[str, str] = {}
    for part in text.split("\n#### ")[1:]:
        m = re.match(r'^([A-Z0-9][A-Z0-9\.\-]{0,9})', part.split("\n")[0])
        if m:
            ticker = m.group(1).upper()
            sections[ticker] = "#### " + part.rstrip()
    return sections


def extract_mimi_entry_zone(section: str) -> str:
    """Try to pull the entry zone / recommended position from a Mimi section."""
    for pattern in [
        r'進場[^|｜\n]*[|｜]\s*([^\n]{2,60})',
        r'第一批[^|｜\n]*[|｜]\s*([^\n]{2,60})',
        r'進場區間[^|｜\n]*[|｜]\s*([^\n]{2,60})',
        r'建議倉位[^|｜\n]*[|｜]\s*([^\n]{2,60})',
    ]:
        m = re.search(pattern, section)
        if m:
            return m.group(1).strip()[:60]
    return "—"


